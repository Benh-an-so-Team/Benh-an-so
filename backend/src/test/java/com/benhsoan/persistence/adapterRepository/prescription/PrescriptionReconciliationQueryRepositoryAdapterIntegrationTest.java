    @Test
    void twoGroupsActAsOrAndReturnBothDiscrepancyCategories() {
        persistPrescription("RX000018", PrescriptionStatus.DISPENSED,
                InterconnectionStatus.FAILED, PERIOD_FROM.plusSeconds(110), PERIOD_FROM.plusSeconds(120));
        persistPrescription("RX000019", PrescriptionStatus.PENDING_DISPENSE,
                InterconnectionStatus.SUCCESS, PERIOD_FROM.plusSeconds(130), PERIOD_FROM.plusSeconds(140));
        persistPrescription("RX000020", PrescriptionStatus.DISPENSED,
                InterconnectionStatus.SUCCESS, PERIOD_FROM.plusSeconds(150), PERIOD_FROM.plusSeconds(160));
        persistPrescription("RX000021", PrescriptionStatus.CANCELLED,
                InterconnectionStatus.NOT_SENT, PERIOD_FROM.plusSeconds(170), null);
        flush();

        Page<PrescriptionReconciliationItemResult> page = search(filter(
                PERIOD_FROM, PERIOD_TO, null,
                new ReconciliationOutcomeGroup(
                        List.of(PrescriptionStatus.PENDING_DISPENSE),
                        List.of(InterconnectionStatus.SUCCESS)),
                new ReconciliationOutcomeGroup(
                        List.of(PrescriptionStatus.DISPENSED, PrescriptionStatus.PARTIALLY_DISPENSED),
                        List.of(InterconnectionStatus.NOT_SENT, InterconnectionStatus.FAILED))));

        assertEquals(2, page.getTotalElements());
        assertTrue(page.getContent().stream().allMatch(PrescriptionReconciliationItemResult::discrepancy));
    }

    @Test
    void countMatchesRowsForEveryFilterShape() {
        persistPrescription("RX000022", PrescriptionStatus.DISPENSED,
                InterconnectionStatus.FAILED, PERIOD_FROM.plusSeconds(200), PERIOD_FROM.plusSeconds(210));
        persistPrescription("RX000023", PrescriptionStatus.PENDING_DISPENSE,
                InterconnectionStatus.SUCCESS, PERIOD_FROM.plusSeconds(220), PERIOD_FROM.plusSeconds(230));
        flush();

        Page<PrescriptionReconciliationItemResult> unfiltered = search(
                filter(PERIOD_FROM, PERIOD_TO, null));
        Page<PrescriptionReconciliationItemResult> byOutcome = search(filter(
                PERIOD_FROM, PERIOD_TO, null,
                new ReconciliationOutcomeGroup(
                        List.of(PrescriptionStatus.DISPENSED),
                        List.of(InterconnectionStatus.FAILED))));
        Page<PrescriptionReconciliationItemResult> byCode = search(
                filter(PERIOD_FROM, PERIOD_TO, "RX000022"));

        assertEquals(2, unfiltered.getTotalElements());
        assertEquals(2, unfiltered.getContent().size());
        assertEquals(1, byOutcome.getTotalElements());
        assertEquals(1, byOutcome.getContent().size());
        assertEquals(1, byCode.getTotalElements());
        assertEquals(1, byCode.getContent().size());
    }

