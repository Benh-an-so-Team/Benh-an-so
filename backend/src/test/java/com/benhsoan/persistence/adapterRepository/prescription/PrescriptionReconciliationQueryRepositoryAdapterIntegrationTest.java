    @Test
    void identicalTimestampsAreTieBrokenByIdDescending() {
        Instant sameInstant = PERIOD_FROM.plusSeconds(500);
        persistPrescription("RX000012", PrescriptionStatus.PENDING_DISPENSE,
                InterconnectionStatus.NOT_SENT, sameInstant, null);
        persistPrescription("RX000013", PrescriptionStatus.PENDING_DISPENSE,
                InterconnectionStatus.NOT_SENT, sameInstant, null);
        flush();

        List<UUID> ids = search(filter(PERIOD_FROM, PERIOD_TO, null)).getContent().stream()
                .map(PrescriptionReconciliationItemResult::prescriptionId)
                .toList();

        assertEquals(2, ids.size());
        assertTrue(compareUnsignedDescending(ids.get(0), ids.get(1)),
                "expected id descending tie break using BINARY(16) unsigned byte ordering");
    }

    /**
     * Ids are stored as BINARY(16) and ordered by the database with unsigned byte comparison,
     * which is not the same as UUID.compareTo (signed long comparison). This mirrors the
     * database semantics so the deterministic tie break is actually verified.
     */
    private static boolean compareUnsignedDescending(UUID left, UUID right) {
        byte[] leftBytes = toBytes(left);
        byte[] rightBytes = toBytes(right);
        for (int index = 0; index < leftBytes.length; index++) {
            int leftUnsigned = leftBytes[index] & 0xFF;
            int rightUnsigned = rightBytes[index] & 0xFF;
            if (leftUnsigned != rightUnsigned) {
                return leftUnsigned > rightUnsigned;
            }
        }
        return false;
    }

    private static byte[] toBytes(UUID value) {
        java.nio.ByteBuffer buffer = java.nio.ByteBuffer.allocate(16);
        buffer.putLong(value.getMostSignificantBits());
        buffer.putLong(value.getLeastSignificantBits());
        return buffer.array();
    }

