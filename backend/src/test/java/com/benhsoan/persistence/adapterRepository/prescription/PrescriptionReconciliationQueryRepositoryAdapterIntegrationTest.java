    private UUID persistPrescription(
            String code,
            PrescriptionStatus status,
            InterconnectionStatus interconnectionStatus,
            Instant prescribedAt,
            Instant interconnectedAt
    ) {
        UUID id = UUID.randomUUID();
        entityManager.persist(PrescriptionEntity.builder()
                .id(id)
                .prescriptionCode(code)
                .medicalRecordId(UUID.randomUUID())
                .status(status)
                .prescribedBy(UUID.randomUUID())
                .prescribedAt(prescribedAt)
                .interconnectionStatus(interconnectionStatus)
                .lastInterconnectionAt(interconnectedAt)
                .lastInterconnectionError(interconnectionStatus == InterconnectionStatus.FAILED
                        ? "gateway timeout"
                        : null)
                .interconnectionReceiptCode(interconnectionStatus == InterconnectionStatus.SUCCESS
                        ? "LT-" + code
                        : null)
                .build());
        return id;
    }

    private void persistDispense(UUID prescriptionId, Instant dispensedAt) {
        entityManager.persist(PrescriptionDispenseItemEntity.builder()
                .id(UUID.randomUUID())
                .prescriptionId(prescriptionId)
                .prescriptionItemId(UUID.randomUUID())
                .medicineId(UUID.randomUUID())
                .medicineBatchId(UUID.randomUUID())
                .dispensedQuantity(1)
                .returnedQuantity(0)
                .dispensedBy(UUID.randomUUID())
                .dispensedAt(dispensedAt)
                .createdAt(dispensedAt)
                .build());
    }

    private void flush() {
        entityManager.flush();
        entityManager.clear();
    }

    private static ReconciliationQueryFilter filter(
            Instant from,
            Instant to,
            String prescriptionCode,
            ReconciliationOutcomeGroup... groups
    ) {
        return new ReconciliationQueryFilter(from, to, prescriptionCode, List.of(groups));
    }

    private Page<PrescriptionReconciliationItemResult> search(ReconciliationQueryFilter filter) {
        return adapter.findByFilter(filter, PageRequest.of(0, 20));
    }

