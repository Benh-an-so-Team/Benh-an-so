    @Test
    void batchedDispenseAggregateFillsTheLatestDispensingInstant() {
        UUID id = persistPrescription("RX000025", PrescriptionStatus.PARTIALLY_DISPENSED,
                InterconnectionStatus.SUCCESS, PERIOD_FROM.plusSeconds(400), null);
        Instant firstDispense = PERIOD_FROM.plusSeconds(410);
        Instant secondDispense = PERIOD_FROM.plusSeconds(420);
        persistDispense(id, firstDispense);
        persistDispense(id, secondDispense);
        flush();

        PrescriptionReconciliationItemResult row = search(filter(PERIOD_FROM, PERIOD_TO, null))
                .getContent().get(0);

        assertEquals(secondDispense, row.lastDispensedAt());
        assertEquals(PrescriptionReconciliationOutcome.CONSISTENT, row.outcome());
        assertFalse(row.discrepancy());
    }

